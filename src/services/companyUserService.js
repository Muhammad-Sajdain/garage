const bcrypt = require('bcrypt');
const db = require('../../models');
const { Op } = require('sequelize');
const profilePictureService = require('./profilePictureService');
const userWelcomeEmailService = require('./userWelcomeEmailService');

const CompanyUser = db.CompanyUser;
const DEFAULT_COMPANY_USER_PASSWORD = 'garage@123';

const resetCompanyUserPassword = async (id) => {
  const companyUser = await CompanyUser.findOne({ where: { id, is_deleted: 0 } });
  if (!companyUser) throw new Error('CompanyUser not found');

  const hashedPassword = await bcrypt.hash(DEFAULT_COMPANY_USER_PASSWORD, 10);
  const [updatedUsers] = await db.Users.update(
    { password: hashedPassword },
    { where: { id: companyUser.user_id, is_deleted: 0 } },
  );
  if (!updatedUsers) throw new Error('Associated user not found');

  const user = await db.Users.findOne({
    where: { id: companyUser.user_id, is_deleted: 0 },
    attributes: ['id', 'name', 'email'],
  });
  try {
    await userWelcomeEmailService.sendPasswordResetEmail({ user });
  } catch (error) {
    console.error('Company employee password reset email failed:', error.message);
  }

  return { success: true, message: 'Password reset successfully' };
};

const listCompanyUsers = async (company_id) => {
  return CompanyUser.findAll({
    where: { company_id, is_deleted: 0 },
    include: [
      {
        model: db.Users,
        as: 'user',
        where: { is_deleted: 0 },
        required: true,
      },
      {
        model: db.Company,
        as: 'company',
        where: { is_deleted: 0 },
        required: false,
      },
      {
        model: db.Role,
        as: 'role',
        where: { is_deleted: 0 },
        required: false,
      },
    ],
    order: [['id', 'ASC']],
  });
};

const getCompanyUserById = async (id, company_id) => {
  const include = [
      {
        model: db.Users,
        as: 'user',
        where: { is_deleted: 0 },
        required: true,
      },
      {
        model: db.Company,
        as: 'company',
        where: { is_deleted: 0 },
        required: false,
      },
      {
        model: db.Role,
        as: 'role',
        where: { is_deleted: 0 },
        required: false,
      },
    ];
  const where = { id, is_deleted: 0 };
  if (company_id !== undefined) where.company_id = company_id;

  const companyUser = await CompanyUser.findOne({ where, include });
  if (companyUser || company_id === undefined) return companyUser;

  // Some callers use the associated users.id instead of company_users.id.
  return CompanyUser.findOne({
    where: { user_id: id, company_id, is_deleted: 0 },
    include,
  });
};

const createCompanyUser = async (payload, file) => {
  const transaction = await db.sequelize.transaction();
  let uploadedLogo;
  let createdUser;
  try {
    const {
      name,
      country,
      state,
      email,
      phone,
      address,
      status = 1,
      company_id,
      role_id,
    } = payload;

    if (!phone || !String(phone).trim()) {
      throw new Error('Phone is required');
    }
    if (!email || !String(email).trim()) {
      throw new Error('Email is required');
    }

    const existingUser = await db.Users.findOne({
      where: { email: String(email).trim() },
      transaction,
    });
    if (existingUser) {
      throw new Error('This email is already exist.');
    }

    let user_id = payload.user_id;

    if (file) uploadedLogo = await profilePictureService.saveProfilePicture(file);

    // If user details are provided, create the User first
    if (name || email) {
      // Company employee credentials are generated by the API, never accepted
      // from the client.
      const hashedPassword = await bcrypt.hash(DEFAULT_COMPANY_USER_PASSWORD, 10);

      const user = await db.Users.create(
        {
          name,
          country,
          state: state ?? '',
          email,
          password: hashedPassword,
          phone,
          address,
          logo: uploadedLogo ?? null,
          status,
          is_deleted: 0,
        },
        { transaction }
      );
      user_id = user.id;
      createdUser = user;
    }

    if (!user_id) {
      throw new Error('User ID is required, or user creation details must be provided');
    }

    const companyUser = await CompanyUser.create(
      {
        user_id,
        company_id,
        role_id,
        status: 1, // status: 1 for company user as requested
        is_deleted: 0,
      },
      { transaction }
    );

    await transaction.commit();
    const result = await getCompanyUserById(companyUser.id);
    if (createdUser) {
      try {
        await userWelcomeEmailService.sendAccountCreatedEmail({ user: createdUser });
      } catch (error) {
        console.error('Company employee welcome email failed:', error.message);
      }
    }
    return result;
  } catch (error) {
    await transaction.rollback();
    if (uploadedLogo) profilePictureService.removeProfilePicture(uploadedLogo);
    else profilePictureService.removeUploadedFile(file);
    throw error;
  }
};

const updateCompanyUser = async (id, payload, file) => {
  const companyUser = await CompanyUser.findOne({
    where: { id, is_deleted: 0 },
  });

  if (!companyUser) {
    throw new Error('CompanyUser not found');
  }

  const previousLogo = (await db.Users.findByPk(companyUser.user_id))?.logo;
  const transaction = await db.sequelize.transaction();
  let uploadedLogo;
  try {
    const {
      name,
      country,
      state,
      email,
      phone,
      address,
      status,
      company_id,
      role_id,
    } = payload;

    const hasProfileUpdate = [name, country, state, email, phone, address]
      .some((value) => value !== undefined);

    if (hasProfileUpdate) {
      if (!phone || !String(phone).trim()) {
        throw new Error('Phone is required');
      }
      if (!email || !String(email).trim()) {
        throw new Error('Email is required');
      }

      const existingUser = await db.Users.findOne({
        where: {
          email: String(email).trim(),
          id: { [Op.ne]: companyUser.user_id },
        },
        transaction,
      });
      if (existingUser) {
        throw new Error('This email is already exist.');
      }
    }

    // Update CompanyUser fields
    const companyUserUpdateData = {};
    if (company_id !== undefined) companyUserUpdateData.company_id = company_id;
    if (role_id !== undefined) companyUserUpdateData.role_id = role_id;
    if (status !== undefined) companyUserUpdateData.status = status;

    if (Object.keys(companyUserUpdateData).length > 0) {
      await companyUser.update(companyUserUpdateData, { transaction });
    }

    // Update associated User fields
    const userUpdateData = {};
    if (file) {
      uploadedLogo = await profilePictureService.saveProfilePicture(file);
      userUpdateData.logo = uploadedLogo;
    } else if (payload.logo === null || payload.remove_logo === 'true') {
      userUpdateData.logo = null;
    }
    if (name !== undefined) userUpdateData.name = name;
    if (country !== undefined) userUpdateData.country = country;
    if (state !== undefined) userUpdateData.state = state;
    if (email !== undefined) userUpdateData.email = email;
    if (phone !== undefined) userUpdateData.phone = phone;
    if (address !== undefined) userUpdateData.address = address;
    if (status !== undefined) userUpdateData.status = status;
    if (Object.keys(userUpdateData).length > 0) {
      await db.Users.update(userUpdateData, {
        where: { id: companyUser.user_id },
        transaction,
      });
    }

    await transaction.commit();
    if (uploadedLogo && previousLogo) profilePictureService.removeProfilePicture(previousLogo);
    if (!uploadedLogo && userUpdateData.logo === null && previousLogo) profilePictureService.removeProfilePicture(previousLogo);
    return getCompanyUserById(id);
  } catch (error) {
    await transaction.rollback();
    if (uploadedLogo) profilePictureService.removeProfilePicture(uploadedLogo);
    else profilePictureService.removeUploadedFile(file);
    throw error;
  }
};

const deleteCompanyUser = async (id) => {
  const companyUser = await CompanyUser.findOne({
    where: { id, is_deleted: 0 },
  });

  if (!companyUser) {
    throw new Error('CompanyUser not found');
  }

  const transaction = await db.sequelize.transaction();
  try {
    await companyUser.update({ is_deleted: 1 }, { transaction });

    await db.Users.update(
      { is_deleted: 1 },
      {
        where: { id: companyUser.user_id },
        transaction,
      }
    );

    await transaction.commit();
    return { success: true, message: 'CompanyUser deleted successfully' };
  } catch (error) {
    await transaction.rollback();
    throw error;
  }
};

module.exports = {
  listCompanyUsers,
  getCompanyUserById,
  createCompanyUser,
  updateCompanyUser,
  deleteCompanyUser,
  resetCompanyUserPassword,
};
