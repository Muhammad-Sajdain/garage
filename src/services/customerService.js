const bcrypt = require('bcrypt');
const db = require('../../models');
const { Op } = require('sequelize');
const customerWelcomeEmailService = require('./customerWelcomeEmailService');

const Customer = db.Customer;
const Role = db.Role;
const DEFAULT_CUSTOMER_PASSWORD = 'garageCustomer@123';

const validateCompanyRole = async (roleId, companyId) => {
  if (!roleId) return;

  const role = await Role.findOne({
    where: { id: roleId, company_id: companyId, is_deleted: 0, status: 1 },
  });
  if (!role) throw new Error('Role must belong to the customer company');
};

const listCustomers = async (company_id, customer_id) => {
  return Customer.findAll({
    where: {
      is_deleted: 0,
      ...(company_id ? { company_id } : {}),
      ...(customer_id ? { id: Number(customer_id) } : {}),
    },
    order: [['id', 'ASC']],
  });
};

const getCustomerById = async (id) => {
  return Customer.findOne({
    where: { id, is_deleted: 0 },
  });
};

const createCustomer = async (payload) => {
  const {
    name,
    email,
    phone,
    address,
    password_reset = 0,
    company_id: payloadCompanyId,
    selectedCompanyId,
    created_by,
    status = 1,
  } = payload;
  const company_id = selectedCompanyId ?? payloadCompanyId;

  if (!phone || !String(phone).trim()) {
    throw new Error('Phone is required');
  }
  if (String(phone).trim().length > 15) {
    throw new Error('Phone must be 15 characters or less');
  }
  if (!email || !String(email).trim()) {
    throw new Error('Email is required');
  }

  const existingCustomer = await Customer.findOne({
    where: { email: String(email).trim() },
  });
  if (existingCustomer) {
    throw new Error('This email is already exist.');
  }

  const customerRole = await Role.findOne({
    where: { company_id, name: 'Customer', is_deleted: 0, status: 1 },
  });
  if (!customerRole) {
    throw new Error('Customer role not found for the selected company');
  }
  const role_id = customerRole.id;

  // Customer credentials are generated by the server; never trust a client-supplied password.
  const hashedPassword = await bcrypt.hash(DEFAULT_CUSTOMER_PASSWORD, 10);
  await validateCompanyRole(role_id, company_id);

  const customer = await Customer.create({
    name,
    email,
    password: hashedPassword,
    phone,
    address,
    password_reset,
    company_id,
    role_id,
    created_by,
    status,
    is_deleted: 0,
  });

  try {
    await customerWelcomeEmailService.sendAccountCreatedEmail({ customer, company_id });
  } catch (error) {
    // Account creation should succeed even if the email provider is temporarily unavailable.
    console.error('Customer account welcome email failed:', error.message);
  }

  return customer;
};

const updateCustomer = async (id, payload) => {
  const customer = await Customer.findOne({
    where: { id, is_deleted: 0 },
  });

  if (!customer) {
    throw new Error('Customer not found');
  }

  const { password: _password, ...updateData } = payload;
  const hasProfileUpdate = ['name', 'email', 'phone', 'address'].some(
    (field) => updateData[field] !== undefined,
  );
  if (hasProfileUpdate) {
    if (!updateData.phone || !String(updateData.phone).trim()) {
      throw new Error('Phone is required');
    }
    if (String(updateData.phone).trim().length > 15) {
      throw new Error('Phone must be 15 characters or less');
    }
    if (!updateData.email || !String(updateData.email).trim()) {
      throw new Error('Email is required');
    }
  }
  if (updateData.email !== undefined) {
    const existingCustomer = await Customer.findOne({
      where: {
        email: String(updateData.email).trim(),
        id: { [Op.ne]: customer.id },
      },
    });
    if (existingCustomer) {
      throw new Error('This email is already exist.');
    }
  }
  await validateCompanyRole(
    updateData.role_id ?? customer.role_id,
    updateData.company_id ?? customer.company_id,
  );

  await customer.update(updateData);
  return getCustomerById(id);
};

const deleteCustomer = async (id) => {
  const customer = await Customer.findOne({
    where: { id, is_deleted: 0 },
  });

  if (!customer) {
    throw new Error('Customer not found');
  }

  await customer.update({ is_deleted: 1 });
  return { success: true, message: 'Customer deleted successfully' };
};

const resetCustomerPassword = async (id) => {
  const customer = await Customer.findOne({
    where: { id, is_deleted: 0 },
  });

  if (!customer) {
    throw new Error('Customer not found');
  }

  const hashedPassword = await bcrypt.hash(DEFAULT_CUSTOMER_PASSWORD, 10);
  await customer.update({ password: hashedPassword });
  try {
    await customerWelcomeEmailService.sendPasswordResetEmail({ customer });
  } catch (error) {
    console.error('Customer password reset email failed:', error.message);
  }
  return { success: true, message: 'Password reset successfully' };
};

module.exports = {
  listCustomers,
  getCustomerById,
  createCustomer,
  updateCustomer,
  deleteCustomer,
  resetCustomerPassword,
};
